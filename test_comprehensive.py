def test_random_50_items():
    # اختيار 50 عنصر عشوائي
    random_items = random.sample(full_menu, 50)
    
    print("🧪 اختبار شامل للنظام مع 50 عنصر عشوائي:")
    print("=" * 80)
    print()
    
    perfect_translations = 0
    good_translations = 0
    needs_improvement = 0
    
    for i, item in enumerate(random_items, 1):
        print(f"🔢 العنصر {i}:")
        print(f"📝 النص العربي: {item}")
        
        # ترجمة العنصر
        result = translate_and_extract_for_search(item)
        
        print(f"🌍 الترجمة الكاملة: {result['full_translation']}")
        print(f"🔍 كلمات البحث (AI Search): {result['search_query']}")
        
        # تقييم جودة الترجمة
        if 'ferakh' not in result['full_translation'] and len(result['search_query'].split()) >= 2:
            quality = "ممتازة ✅"
            perfect_translations += 1
        elif len(result['search_query'].split()) >= 1:
            quality = "جيدة ✓"
            good_translations += 1
        else:
            quality = "تحتاج تحسين ❌"
            needs_improvement += 1
            
        print(f"📊 جودة الترجمة: {quality}")
        print("-" * 60)
        print()
    
    print("📈 ملخص النتائج:")
    print(f"✅ ترجمات ممتازة: {perfect_translations}/50 ({perfect_translations*2}%)")
    print(f"✓ ترجمات جيدة: {good_translations}/50 ({good_translations*2}%)")
    print(f"❌ تحتاج تحسين: {needs_improvement}/50 ({needs_improvement*2}%)")
    print(f"🎯 إجمالي النجاح: {(perfect_translations + good_translations)*2}%")

if __name__ == "__main__":
    test_random_50_items()
